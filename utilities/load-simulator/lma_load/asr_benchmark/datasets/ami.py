"""AMI Meeting Corpus meetings as stereo LMA recordings with STM ground truth.

The reference transcripts and the manifest are packaged in ``ami/``; the headset audio is
downloaded from the AMI mirror on first use, checked against the manifest's SHA-256, and
mixed into a stereo WAV: channel 0 the other participants, channel 1 the meeting's host.

    python -m lma_load.asr_benchmark.datasets.ami package IS1009c A \\
        --annotations /tmp/ami/annotations --headsets /tmp/ami/audio/IS1009c
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
import tempfile
import urllib.request
import wave
from pathlib import Path
from typing import Any

DATA_DIR = Path(__file__).parent / "ami"
MANIFEST = DATA_DIR / "manifest.json"
MIRROR = "https://groups.inf.ed.ac.uk/ami/AMICorpusMirror/amicorpus"
SAMPLE_RATE = 16000
UTTERANCE_GAP_S = 1.0
GATE_PAD_S = 0.3
MIX_GAIN_TENTHS = 9
TARGET_SPEECH_RMS = 2000
PEAK_LIMIT = 24000

WORD_RE = re.compile(r'<w [^>]*starttime="([\d.]+)"[^>]*endtime="([\d.]+)"([^>]*)>([^<]*)</w>')
SPEAKER_RE = re.compile(r'<speaker [^>]*channel="(\d+)"[^>]*nxt_agent="(\w)"[^>]*role="(\w+)"')


def manifest() -> dict[str, Any]:
    return json.loads(MANIFEST.read_text())


def reference_path(meeting: str) -> Path:
    return DATA_DIR / f"{meeting}.stm"


def headset_url(meeting: str, channel: str) -> str:
    return f"{MIRROR}/{meeting}/audio/{meeting}.Headset-{channel}.wav"


def read_words(xml: str) -> list[tuple[float, float, str]]:
    words: list[tuple[float, float, str]] = []
    for start, end, attrs, text in WORD_RE.findall(xml):
        text = html.unescape(text).strip()
        if not text:
            continue
        if 'punc="true"' in attrs and words:
            s, e, previous = words[-1]
            words[-1] = (s, e, previous + text)
        elif 'punc="true"' not in attrs:
            words.append((float(start), float(end), text))
    return words


def utterances(
    words: list[tuple[float, float, str]], gap: float = UTTERANCE_GAP_S
) -> list[tuple[float, float, str]]:
    out: list[list[Any]] = []
    for start, end, text in words:
        if out and start - out[-1][1] <= gap:
            out[-1][1] = max(out[-1][1], end)
            out[-1][2].append(text)
        else:
            out.append([start, end, [text]])
    return [(s, e, " ".join(t)) for s, e, t in out]


def build_stm(
    meeting: str, host: str, speakers: dict[str, str], words_by_speaker: dict[str, str]
) -> str:
    lines = [
        f";; AMI Meeting Corpus {meeting}, CC BY 4.0. Channel 1 is {host} (the host), channel 0 the others.",
        ";; Generated by lma_load.asr_benchmark.datasets.ami from the manual word annotations 1.6.2.",
    ]
    rows = []
    for letter, xml in words_by_speaker.items():
        channel = "1" if letter == host else "0"
        for start, end, text in utterances(read_words(xml)):
            rows.append(
                (
                    channel,
                    start,
                    f"{meeting} {channel} {meeting}_{letter} {start:.2f} {end:.2f} {text}",
                )
            )
    rows.sort(key=lambda r: (r[0], r[1]))
    return "\n".join(lines + [r[2] for r in rows]) + "\n"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _read_mono(path: Path):
    import numpy as np

    with wave.open(str(path), "rb") as wf:
        if (wf.getframerate(), wf.getnchannels(), wf.getsampwidth()) != (SAMPLE_RATE, 1, 2):
            raise ValueError(f"{path}: expected 16 kHz mono 16-bit")
        return np.frombuffer(wf.readframes(wf.getnframes()), dtype="<i2").astype(np.int32)


def _gate(samples, spans: list[tuple[float, float]]):
    import numpy as np

    mask = np.zeros(len(samples), dtype=bool)
    for start, end in spans:
        lo = max(0, int((start - GATE_PAD_S) * SAMPLE_RATE))
        hi = min(len(samples), int((end + GATE_PAD_S) * SAMPLE_RATE))
        mask[lo:hi] = True
    return np.where(mask, samples, 0)


def _level(samples):
    import math

    import numpy as np

    active = samples[samples != 0].astype(np.int64)
    if not len(active):
        return samples
    rms = math.isqrt(int(np.sum(active * active)) // len(active)) or 1
    magnitudes = np.abs(active)
    rank = min(len(magnitudes) - 1, len(magnitudes) * 9999 // 10000)
    peak = int(np.partition(magnitudes, rank)[rank]) or 1
    gain = min(TARGET_SPEECH_RMS * 1000 // rms, PEAK_LIMIT * 1000 // peak)
    return samples * gain // 1000


def _spans_by_speaker(stm: str) -> dict[str, list[tuple[float, float]]]:
    spans: dict[str, list[tuple[float, float]]] = {}
    for line in stm.splitlines():
        if not line or line.startswith(";;"):
            continue
        fields = line.split(maxsplit=5)
        spans.setdefault(fields[2].rsplit("_", 1)[1], []).append(
            (float(fields[3]), float(fields[4]))
        )
    return spans


def mix(headsets: dict[str, Path], host: str, stm: str, out: Path) -> Path:
    import numpy as np

    spans = _spans_by_speaker(stm)
    tracks = {
        letter: _level(_gate(_read_mono(path), spans.get(letter, [])))
        for letter, path in headsets.items()
    }
    length = max(len(t) for t in tracks.values())
    padded = {k: np.pad(v.astype(np.int64), (0, length - len(v))) for k, v in tracks.items()}
    meeting = sum(v for k, v in padded.items() if k != host)
    stereo = np.stack([meeting, padded[host]], axis=1) * MIX_GAIN_TENTHS // 10
    pcm = np.clip(stereo, -32768, 32767).astype("<i2")
    out.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(out), "wb") as wf:
        wf.setnchannels(2)
        wf.setsampwidth(2)
        wf.setframerate(SAMPLE_RATE)
        wf.writeframes(pcm.tobytes())
    return out


def _download(url: str, dest: Path, expected: str) -> None:
    if dest.exists() and sha256(dest) == expected:
        return
    if not url.startswith(f"{MIRROR}/"):
        raise ValueError(f"refusing to download from {url}")
    dest.parent.mkdir(parents=True, exist_ok=True)
    partial = dest.with_suffix(".part")
    with urllib.request.urlopen(url, timeout=120) as response, partial.open("wb") as handle:
        for block in iter(lambda: response.read(1 << 20), b""):
            handle.write(block)
    actual = sha256(partial)
    if actual != expected:
        partial.unlink()
        raise ValueError(f"{url}: SHA-256 {actual} does not match the manifest's {expected}")
    partial.rename(dest)


def build_wav(meeting: str, cache_dir: Path) -> Path:
    entry = manifest()["meetings"][meeting]
    out = cache_dir / "ami" / f"{meeting}.stereo.wav"
    if out.exists() and sha256(out) == entry["stereoSha256"]:
        return out
    headsets: dict[str, Path] = {}
    for letter, info in entry["speakers"].items():
        path = cache_dir / "ami" / meeting / f"{meeting}.Headset-{info['headset']}.wav"
        _download(headset_url(meeting, info["headset"]), path, info["sha256"])
        headsets[letter] = path
    mix(headsets, entry["host"], reference_path(meeting).read_text(), out)
    actual = sha256(out)
    if actual != entry["stereoSha256"]:
        raise ValueError(
            f"{out}: mixed audio SHA-256 {actual} differs from the manifest's {entry['stereoSha256']}"
        )
    return out


def package(
    meeting: str, host: str, annotations: Path, headsets_dir: Path, scratch: Path
) -> dict[str, Any]:
    meetings_xml = (annotations / "corpusResources" / "meetings.xml").read_text(
        encoding="iso-8859-1"
    )
    block = re.search(rf'observation="{meeting}".*?</meeting>', meetings_xml, re.DOTALL)
    if not block:
        raise ValueError(f"{meeting} is not in meetings.xml")
    speakers = {
        letter: {"headset": channel, "role": role}
        for channel, letter, role in SPEAKER_RE.findall(block.group(0))
    }
    words = {
        letter: (annotations / "words" / f"{meeting}.{letter}.words.xml").read_text(
            encoding="iso-8859-1"
        )
        for letter in speakers
    }
    stm = build_stm(meeting, host, {k: v["headset"] for k, v in speakers.items()}, words)
    reference_path(meeting).write_text(stm)
    headsets = {}
    for letter, info in speakers.items():
        path = headsets_dir / f"{meeting}.Headset-{info['headset']}.wav"
        info["sha256"] = sha256(path)
        headsets[letter] = path
    stereo = mix(headsets, host, stm, scratch / f"{meeting}.stereo.wav")
    with wave.open(str(stereo), "rb") as wf:
        seconds = wf.getnframes() / wf.getframerate()
    entry = {
        "host": host,
        "hostRole": speakers[host]["role"],
        "seconds": round(seconds, 2),
        "speakers": speakers,
        "stereoSha256": sha256(stereo),
    }
    data = (
        manifest()
        if MANIFEST.exists()
        else {"corpus": "AMI Meeting Corpus", "licence": "CC BY 4.0", "meetings": {}}
    )
    data["meetings"][meeting] = entry
    MANIFEST.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
    return entry


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = parser.add_subparsers(dest="command", required=True)
    pack = sub.add_parser("package", help="write a meeting's STM reference and manifest entry")
    pack.add_argument("meeting")
    pack.add_argument("host", help="AMI speaker letter to put on the microphone channel")
    pack.add_argument("--annotations", type=Path, required=True)
    pack.add_argument("--headsets", type=Path, required=True)
    pack.add_argument("--scratch", type=Path, default=Path(tempfile.gettempdir()) / "ami-stereo")
    build = sub.add_parser("build", help="download and mix a packaged meeting")
    build.add_argument("meeting")
    build.add_argument(
        "--cache-dir", type=Path, default=Path.home() / ".cache" / "lma-asr-benchmark"
    )
    args = parser.parse_args(argv)
    if args.command == "package":
        print(
            json.dumps(
                package(args.meeting, args.host, args.annotations, args.headsets, args.scratch),
                indent=2,
            )
        )
    else:
        print(build_wav(args.meeting, args.cache_dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
